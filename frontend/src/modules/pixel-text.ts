export interface PixelTextOptions {
  shade?: ContributionLevel;
  spacing?: number;
  maxWidth?: number;
}

export function renderTextToMatrix(
  input: string,
  options: PixelTextOptions = {}
): ContributionLevel[][] {
  const shade: ContributionLevel = options.shade && options.shade > 0 ? options.shade : 4;
  const spacing = Math.max(0, Math.min(3, options.spacing ?? 1));
  const maxWidth = Math.max(1, Math.min(53, options.maxWidth ?? 53));
  const normalized = input.trim().toUpperCase();

  if (!normalized) {
    return Array.from({ length: 7 }, () => new Array<ContributionLevel>(1).fill(0));
  }

  const rows: ContributionLevel[][] = Array.from({ length: 7 }, () => []);

  for (let idx = 0; idx < normalized.length; idx++) {
    const ch = normalized[idx];
    const glyph = FONT_5X7[ch] || FONT_5X7['?'];
    const glyphWidth = glyph[0].length;

    if (idx > 0 && spacing > 0) {
      for (let r = 0; r < 7; r++) {
        for (let s = 0; s < spacing; s++) {
          rows[r].push(0);
        }
      }
    }

    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < glyphWidth; c++) {
        rows[r].push(glyph[r][c] === '1' ? shade : 0);
      }
    }
  }

  const clampedWidth = Math.max(1, Math.min(maxWidth, rows[0].length));
  return rows.map((row) => row.slice(0, clampedWidth));
}
