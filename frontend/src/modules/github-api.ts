import { ArtConfig, RepoDetails, ContributionLevel, UserContributionData } from '../types';
import { clearAuth } from './auth-pkce';

export function toBase64Utf8(str: string): string {
  const bytes = new TextEncoder().encode(str);
  let bin = '';
  for (let i = 0; i < bytes.length; i++) {
    bin += String.fromCharCode(bytes[i]);
  }
  return btoa(bin);
}

export function fromBase64Utf8(b64: string): string {
  const bin = atob(b64.replace(/\s/g, ''));
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) {
    bytes[i] = bin.charCodeAt(i);
  }
  return new TextDecoder().decode(bytes);
}

export async function checkRepoExists(
  token: string,
  owner: string,
  repo: string
): Promise<RepoDetails | null> {
  const res = await fetch(`https://api.github.com/repos/${owner}/${repo}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github.v3+json'
    }
  });

  if (res.status === 404) {
    return null;
  }

  if (!res.ok) {
    if (res.status === 401) {
      clearAuth();
      window.dispatchEvent(new CustomEvent('gitstamp:auth-expired'));
    }
    throw new Error(`Failed to check repository: ${res.statusText}`);
  }

  const data = await res.json();
  return {
    name: data.name,
    owner: data.owner.login,
    html_url: data.html_url,
    default_branch: data.default_branch || 'main'
  };
}

export async function createPublicRepo(
  token: string,
  repoName: string
): Promise<RepoDetails> {
  const res = await fetch('https://api.github.com/user/repos', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github.v3+json',
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      name: repoName,
      private: false,
      auto_init: true,
      description: 'Dynamic GitHub contribution graph artwork generated by GitStamp'
    })
  });

  if (!res.ok) {
    if (res.status === 401) {
      clearAuth();
      window.dispatchEvent(new CustomEvent('gitstamp:auth-expired'));
    }
    const errorData = await res.json().catch(() => ({}));
    throw new Error(errorData.message || `Failed to create repository: ${res.statusText}`);
  }

  const data = await res.json();
  return {
    name: data.name,
    owner: data.owner.login,
    html_url: data.html_url,
    default_branch: data.default_branch || 'main'
  };
}

export async function getFile(
  token: string,
  owner: string,
  repo: string,
  path: string
): Promise<{ sha: string; content: string } | null> {
  const res = await fetch(`https://api.github.com/repos/${owner}/${repo}/contents/${path}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github.v3+json'
    }
  });

  if (res.status === 404) {
    return null;
  }

  if (!res.ok) {
    if (res.status === 401) {
      clearAuth();
      window.dispatchEvent(new CustomEvent('gitstamp:auth-expired'));
    }
    throw new Error(`Failed to fetch file ${path}: ${res.statusText}`);
  }

  const data = await res.json();
  return {
    sha: data.sha,
    content: fromBase64Utf8(data.content)
  };
}

export async function putFile(
  token: string,
  owner: string,
  repo: string,
  path: string,
  contentStr: string,
  message: string,
  sha?: string
): Promise<void> {
  const body: Record<string, unknown> = {
    message,
    content: toBase64Utf8(contentStr)
  };

  if (sha) {
    body.sha = sha;
  }

  const res = await fetch(`https://api.github.com/repos/${owner}/${repo}/contents/${path}`, {
    method: 'PUT',
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github.v3+json',
      'Content-Type': 'application/json'
    },
    body: JSON.stringify(body)
  });

  if (!res.ok) {
    if (res.status === 401) {
      clearAuth();
      window.dispatchEvent(new CustomEvent('gitstamp:auth-expired'));
    }
    const errorData = await res.json().catch(() => ({}));
    throw new Error(
      errorData.message || `Failed to save ${path}: ${res.statusText}`
    );
  }
}

export async function triggerWorkflow(
  token: string,
  owner: string,
  repo: string,
  workflowFileName: string = 'render.yml',
  ref: string = 'main'
): Promise<void> {
  const res = await fetch(
    `https://api.github.com/repos/${owner}/${repo}/actions/workflows/${workflowFileName}/dispatches`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github.v3+json',
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        ref
      })
    }
  );

  if (!res.ok) {
    const errorData = await res.json().catch(() => ({}));
    throw new Error(
      errorData.message || `Failed to trigger workflow: ${res.statusText}`
    );
  }
}

export async function fetchExistingArt(
  token: string,
  owner: string,
  repo: string
): Promise<{ config: ArtConfig; sha: string } | null> {
  const file = await getFile(token, owner, repo, 'art.json');
  if (!file) {
    return null;
  }
  try {
    const config = JSON.parse(file.content) as ArtConfig;
    return {
      config,
      sha: file.sha
    };
  } catch {
    return null;
  }
}

