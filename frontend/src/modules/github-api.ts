export async function fetchUserContributions(
  token: string,
  year?: number
): Promise<UserContributionData | null> {
  const now = new Date();
  const currentYear = now.getUTCFullYear();
  const isPastYear = typeof year === 'number' && year < currentYear;

  let query: string;
  let variables: Record<string, string> = {};

  if (isPastYear) {
    query = `
      query($from: DateTime!, $to: DateTime!) {
        viewer {
          contributionsCollection(from: $from, to: $to) {
            contributionYears
            contributionCalendar {
              totalContributions
              weeks {
                contributionDays {
                  date
                  contributionCount
                  contributionLevel
                }
              }
            }
          }
        }
      }
    `;
    variables = {
      from: `${year}-01-01T00:00:00Z`,
      to: `${year}-12-31T23:59:59Z`
    };
  } else {
    query = `
      query {
        viewer {
          contributionsCollection {
            contributionYears
            contributionCalendar {
              totalContributions
              weeks {
                contributionDays {
                  date
                  contributionCount
                  contributionLevel
                }
              }
            }
          }
        }
      }
    `;
  }

  try {
    const res = await fetch('https://api.github.com/graphql', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
        'User-Agent': 'GitStamp'
      },
      body: JSON.stringify({ query, variables })
    });

    if (!res.ok) {
      if (res.status === 401) {
        clearAuth();
        window.dispatchEvent(new CustomEvent('gitstamp:auth-expired'));
      }
      return null;
    }

    const data = await res.json();
    const collection = data?.data?.viewer?.contributionsCollection;
    const calendar = collection?.contributionCalendar;
    if (!calendar || !calendar.weeks) {
      return null;
    }

    const rawYears = collection?.contributionYears;
    const years: number[] = Array.isArray(rawYears)
      ? rawYears.map(Number).filter((n) => Number.isFinite(n))
      : [];

    const levelMap: Record<string, ContributionLevel> = {
      NONE: 0,
      FIRST_QUARTILE: 1,
      SECOND_QUARTILE: 2,
      THIRD_QUARTILE: 3,
      FOURTH_QUARTILE: 4
    };

    const targetWeeks = isPastYear ? calendar.weeks : calendar.weeks.slice(-53);
    const matrix: ContributionLevel[][] = [];

    for (let c = 0; c < 53; c++) {
      matrix[c] = [0, 0, 0, 0, 0, 0, 0];
      const week = targetWeeks[c];
      if (week && week.contributionDays) {
        for (const day of week.contributionDays) {
          const d = new Date(day.date + 'T00:00:00Z');
          const dayOfWeek = d.getUTCDay();
          if (dayOfWeek >= 0 && dayOfWeek < 7) {
            matrix[c][dayOfWeek] = levelMap[day.contributionLevel] || 0;
          }
        }
      }
    }

    return {
      totalContributions: calendar.totalContributions || 0,
      matrix,
      years
    };
  } catch {
    return null;
  }
}

export async function checkAppInstallation(
  token: string,
  username: string
): Promise<boolean | null> {
  try {
    const res = await fetch('https://api.github.com/user/installations', {
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/vnd.github+json'
      }
    });

    if (res.status === 401) {
      clearAuth();
      window.dispatchEvent(new CustomEvent('gitstamp:auth-expired'));
      return null;
    }

    if (!res.ok) {
      return null;
    }

    const data = await res.json();
    const installations = Array.isArray(data?.installations) ? data.installations : [];
    return installations.some(
      (inst: { account?: { login?: string } }) =>
        typeof inst?.account?.login === 'string' &&
        inst.account.login.toLowerCase() === username.toLowerCase()
    );
  } catch {
    return null;
  }
}
